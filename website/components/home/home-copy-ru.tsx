const HELLO_WORLD = `import { z } from "zod";
import { App, secureHeaders, rateLimit, requestId } from "@daloyjs/core";
import { serve } from "@daloyjs/core/node";

const app = new App({ bodyLimitBytes: 1 << 20, requestTimeoutMs: 5_000 });

// new App() уже автоматически применяет requestId() и secureHeaders();
// явные вызовы здесь только настраивают (и заменяют) значения по умолчанию.
app.use(requestId());
app.use(secureHeaders());
app.use(rateLimit({ windowMs: 60_000, max: 120 })); // по IP клиента по умолчанию; за прокси задайте behindProxy или keyGenerator

app.get(
  "/books/:id",
  {
    request: { params: z.object({ id: z.string() }) },
    responses: {
      200: { description: "Найдено", body: z.object({ id: z.string(), title: z.string() }) },
      404: { description: "Не найдено" },
    },
  },
  async ({ params }) => ({
    status: 200,
    body: { id: params.id, title: \`Книга \${params.id}\` },
  }),
);

serve(app, { port: 3000 });`;

